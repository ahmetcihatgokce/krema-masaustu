"""Build the desktop pet's textures, recorded cues and icon from editable media."""
from pathlib import Path
import wave
from PIL import Image

root = Path(__file__).resolve().parents[1]
media, assets = root / "media", root / "assets"
assets.mkdir(exist_ok=True)
sprites = [
    ("AWAKE","awake",428,454), ("HISS","hiss",428,454),
    ("SLEEP","sleep",394,252), ("WALK","walk",486,326),
    ("BOARD","keyboard",314,98), ("MOUSE","mouse",80,86),
    ("MOUSE_LEFT","mouse-left",80,86), ("MOUSE_RIGHT","mouse-right",80,86)
]
sounds = [("STROKE","oksama"), ("HISS","tislama"), ("SLEEP","uyku")]
blob = bytearray()
geometry = []
for identifier, name, w, h in sprites:
    path = media / (name + ".png")
    with Image.open(path) as source:
        if source.mode != "RGBA" or source.size != (w,h):
            raise SystemExit(f"{path.name}: expected transparent RGBA PNG {w} x {h}")
        geometry.append(f"    {{{w}, {h}, {len(blob)}}},")
        blob.extend(source.convert("RGBa").tobytes("raw", "BGRa"))
header = ["/* Generated by python tools/pack.py. */", "#pragma once", "#include <stdint.h>",
          "extern const unsigned char krema_asset_bytes[];",
          "enum SpriteId { " + ", ".join(s[0] for s in sprites) + ", SPRITE_COUNT };",
          "typedef struct { int width, height; uint32_t offset; } SpriteInfo;",
          "static const SpriteInfo sprites[SPRITE_COUNT] = {", *geometry, "};"]
for identifier, name in sounds:
    path = media / (name + ".wav")
    with wave.open(str(path), "rb") as stream:
        if stream.getcomptype() != "NONE" or stream.getsampwidth()!=2 or stream.getnchannels() not in (1,2) or stream.getnframes()<=0:
            raise SystemExit(f"{path.name}: expected nonempty mono or stereo 16-bit PCM WAV")
        duration = stream.getnframes() / stream.getframerate()
    data = path.read_bytes()
    blob.extend(bytes((-len(blob)) % 4))
    header.extend([f"#define {identifier}_OFFSET {len(blob)}", f"#define {identifier}_SIZE {len(data)}",
                   f"#define {identifier}_SECONDS {duration:.6f}"])
    blob.extend(data)
(assets / "krema.bin").write_bytes(blob)
(root / "src" / "media_data.h").write_text("\n".join(header)+"\n", encoding="utf-8")
with Image.open(media / "awake.png") as awake:
    head=awake.crop((108,0,408,300)).resize((232,232),Image.Resampling.LANCZOS)
    icon=Image.new("RGBA",(256,256));icon.alpha_composite(head,(12,12))
    icon.save(assets/"Krema.ico",sizes=[(16,16),(24,24),(32,32),(48,48),(64,64),(128,128),(256,256)])
print("Packed 8 sprites and 3 recordings.")
